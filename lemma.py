def _add_overview_charts(ws, cfg, ov_df):
    n = ov_df.shape[0]
    cols = list(ov_df.columns)
    group_col = 1
    cohesion_col = cols.index(cfg['metric_col_b']) + 1
    baseline_col = cols.index(cfg['baseline_col_b']) + 1
    size_col = cols.index('Number of Books') + 1
    cats = Reference(ws, min_col=group_col, min_row=2, max_row=n + 1)
    anchor_row = n + 4
    ws.cell(row=anchor_row - 1, column=1, value="Charts").font = Font(bold=True, size=12)

    # Chart 1: cohesion vs. baseline (bar + reference line)
    bar = BarChart()
    bar.title = f"{cfg['metric_col_b']} vs. Baseline"
    bar.y_axis.title = "Distance"
    bar.x_axis.title = cfg['group_noun']
    bar.add_data(Reference(ws, min_col=cohesion_col, min_row=1, max_row=n + 1), titles_from_data=True)
    bar.set_categories(cats)
    line = LineChart()
    line.add_data(Reference(ws, min_col=baseline_col, min_row=1, max_row=n + 1), titles_from_data=True)
    line.set_categories(cats)
    bar += line
    bar.height, bar.width = 9, 18
    ws.add_chart(bar, f"A{anchor_row}")

    # Chart 2: reliability breakdown (pie), fed by a small side table
    counts = ov_df['Reliability'].value_counts()
    sc = ov_df.shape[1] + 3
    ws.cell(row=1, column=sc, value='Reliability').font = HEADER_FONT
    ws.cell(row=1, column=sc).fill = HEADER_FILL
    ws.cell(row=1, column=sc + 1, value='Count').font = HEADER_FONT
    ws.cell(row=1, column=sc + 1).fill = HEADER_FILL
    for i, (k, v) in enumerate(counts.items(), start=2):
        ws.cell(row=i, column=sc, value=k)
        ws.cell(row=i, column=sc + 1, value=int(v))
    ws.column_dimensions[get_column_letter(sc)].width = 22
    ws.column_dimensions[get_column_letter(sc + 1)].width = 10
    pie = PieChart()
    pie.title = "Reliability Breakdown"
    pie.add_data(Reference(ws, min_col=sc + 1, min_row=1, max_row=1 + len(counts)), titles_from_data=True)
    pie.set_categories(Reference(ws, min_col=sc, min_row=2, max_row=1 + len(counts)))
    pie.height, pie.width = 9, 10
    ws.add_chart(pie, f"N{anchor_row}")

    # Chart 3: group size
    bar2 = BarChart()
    bar2.title = f"Number of Books per {cfg['group_noun']}"
    bar2.add_data(Reference(ws, min_col=size_col, min_row=1, max_row=n + 1), titles_from_data=True)
    bar2.set_categories(cats)
    bar2.height, bar2.width = 9, 18
    ws.add_chart(bar2, f"A{anchor_row + 20}")

    # Chart 4: corpus composition, stacked (Clusters workbook only)
    if cfg['show_corpus_breakdown']:
        m_col = cols.index('Mikra Books') + 1
        stacked = BarChart()
        stacked.type = "col"
        stacked.grouping = "stacked"
        stacked.overlap = 100
        stacked.title = f"Corpus Composition per {cfg['group_noun']}"
        stacked.add_data(Reference(ws, min_col=m_col, max_col=m_col + 2, min_row=1, max_row=n + 1),
                          titles_from_data=True)
        stacked.set_categories(cats)
        stacked.height, stacked.width = 9, 18
        ws.add_chart(stacked, f"N{anchor_row + 20}")


def _build_explore_sheet(ws, cfg, ov_df, top_x, dist_x, gap_x):
    ws.sheet_view.showGridLines = False
    n = ov_df.shape[0]
    gn = cfg['group_noun']

    ws.merge_cells('A1:L1')
    ws.cell(row=1, column=1, value=f"Explore a {gn}").font = Font(bold=True, size=16, color='1F4E78')
    ws.merge_cells('A2:L2')
    c2 = ws.cell(row=2, column=1,
                 value=f"Pick a {gn.lower()} below \u2014 the tables and charts update automatically.")
    c2.alignment = Alignment(wrap_text=True)

    ws.cell(row=3, column=1, value=f"Choose a {gn}:").font = Font(bold=True)
    ws.cell(row=3, column=2, value=ov_df[gn].iloc[0])
    dv = DataValidation(type="list", formula1=f"='{cfg['sheet_overview']}'!$A$2:$A${n + 1}", allow_blank=False)
    ws.add_data_validation(dv)
    dv.add("B3")

    sections = [
        (cfg['sheet_top'], top_x, 'Top Words', 1),
        (cfg['sheet_dist'], dist_x, 'Distinctive Words', 5),
        (cfg['sheet_gap'], gap_x, 'Gap Words', 9),
    ]

    for sheet_name, df_x, title, start_col in sections:
        cols_x = list(df_x.columns)
        score_label = [c for c in cols_x if c in ('Importance Score', 'Distinctiveness Score', 'Gap Score')][0]
        word_letter = get_column_letter(cols_x.index('Word') + 1)
        score_letter = get_column_letter(cols_x.index(score_label) + 1)

        ws.cell(row=5, column=start_col, value=title).font = Font(bold=True, size=12)
        headers = ['Rank', 'Word', score_label]
        for off, h in enumerate(headers):
            cell = ws.cell(row=6, column=start_col + off, value=h)
            cell.font = HEADER_FONT
            cell.fill = HEADER_FILL

        for i in range(EXPLORE_TOP_N):
            r = 7 + i
            ws.cell(row=r, column=start_col, value=i + 1)
            ws.cell(row=r, column=start_col + 1,
                    value=f"=IFERROR(INDEX('{sheet_name}'!${word_letter}:${word_letter},"
                          f"MATCH($B$3,'{sheet_name}'!$A:$A,0)+{i}),\"\")")
            ws.cell(row=r, column=start_col + 2,
                    value=f"=IFERROR(INDEX('{sheet_name}'!${score_letter}:${score_letter},"
                          f"MATCH($B$3,'{sheet_name}'!$A:$A,0)+{i}),\"\")")

        chart = BarChart()
        chart.type = "bar"
        chart.title = title
        chart.add_data(Reference(ws, min_col=start_col + 2, min_row=6, max_row=6 + EXPLORE_TOP_N),
                        titles_from_data=True)
        chart.set_categories(Reference(ws, min_col=start_col + 1, min_row=7, max_row=6 + EXPLORE_TOP_N))
        chart.height, chart.width = 8, 10
        ws.add_chart(chart, f"{get_column_letter(start_col)}18")

    widths = [6, 26, 14, 3, 6, 26, 16, 3, 6, 26, 12, 3]
    for col, w in zip('ABCDEFGHIJKL', widths):
        ws.column_dimensions[col].width = w



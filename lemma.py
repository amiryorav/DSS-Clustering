# ── Corpus-purity verdict per book (3-view neighbour cross-check) ──────────
def corpus_purity(book, k=TOP_K_NN):
    own_corpus = book_corpus_map.get(book, 'unknown')
    raw_nn  = get_top_neighbors(book, cos_raw, k)
    svd_nn  = get_top_neighbors(book, cos_svd, k)
    ward_nn = get_top_neighbors(book, ward_dist, k)

    def frac_same(nn_list):
        if not nn_list:
            return np.nan
        return sum(1 for b in nn_list if book_corpus_map.get(b) == own_corpus) / len(nn_list)

    fracs = {'raw': frac_same(raw_nn), 'svd': frac_same(svd_nn), 'ward': frac_same(ward_nn)}
    views_hit = sum(1 for f in fracs.values() if not np.isnan(f) and f >= 0.5)
    if views_hit >= 2:
        verdict = '✅ Typical'
    elif views_hit == 1:
        verdict = '⚠️ Mixed'
    else:
        verdict = '❌ Outlier'

    valid_fracs = [f for f in fracs.values() if not np.isnan(f)]
    purity_score = float(np.mean(valid_fracs)) if valid_fracs else np.nan

    neighbor_corpora = [book_corpus_map.get(b, 'unknown') for b in svd_nn]
    dom_neighbor_corpus = max(set(neighbor_corpora), key=neighbor_corpora.count) if neighbor_corpora else 'unknown'

    return {'verdict': verdict, 'purity_score': purity_score, 'fracs': fracs,
            'svd_nn': svd_nn, 'dom_neighbor_corpus': dom_neighbor_corpus}


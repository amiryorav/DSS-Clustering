def build_phase_dataframes(cfg, groups, nn_members_of, nearest_group_of, corpus_of,
                            metric_raw_of, metric_svd_of, baseline_raw, baseline_svd,
                            verdict_of=None, purity_of=None, top_n=TOP_N_PAPER):
    """Builds the 4 raw (full-precision, CSV-ready) DataFrames for one phase."""
    top_rows, dist_rows, gap_rows, index_rows = [], [], [], []

    for gid, members in groups.items():
        nn_members = nn_members_of.get(gid, [])
        nn_label = nearest_group_of.get(gid, 'N/A')
        other_books = [b for b in books_all if b not in members]

        top = shared_lemmas(members, n=top_n)
        pos_rest, neg_rest = diff_lemmas(members, other_books, n=top_n)
        pos_nn, neg_nn = diff_lemmas(members, nn_members, n=top_n)
        gap = neg_nn.abs()   # already sorted biggest-gap-first by diff_lemmas' nsmallest

        row_common = {'phase': cfg['phase_key'], 'group_id': gid, 'group_size': len(members),
                      'corpus': corpus_of.get(gid, ''), 'nearest_group': nn_label}

        for rank, (lemma, val) in enumerate(top.items(), start=1):
            top_rows.append({**row_common, 'rank': rank, 'lemma': lemma, 'mean_tfidf': val})
        for rank, (lemma, val) in enumerate(pos_rest.items(), start=1):
            dist_rows.append({**row_common, 'rank': rank, 'lemma': lemma, 'delta_tfidf_vs_rest': val})
        for rank, (lemma, val) in enumerate(gap.items(), start=1):
            gap_rows.append({**row_common, 'rank': rank, 'lemma': lemma, 'abs_delta_tfidf_vs_nearest': val})

        m_raw, m_svd = metric_raw_of.get(gid, np.nan), metric_svd_of.get(gid, np.nan)
        verdict = verdict_of.get(gid) if verdict_of else _verdict_for_group(members)

        idx_row = {
            'phase': cfg['phase_key'], 'group_id': gid, 'group_size': len(members),
            'corpus': corpus_of.get(gid, ''), 'nearest_group': nn_label,
            'metric': cfg['metric_label'], 'metric_raw': m_raw, 'metric_svd': m_svd,
            'baseline_raw': baseline_raw, 'baseline_svd': baseline_svd,
            'better_than_baseline': bool(m_svd < baseline_svd) if not np.isnan(m_svd) else None,
            'verdict': verdict,
            'purity_score': purity_of.get(gid, np.nan) if purity_of else np.nan,
        }
        if cfg['show_books_list']:
            idx_row['books_in_group'] = ', '.join(sorted(members))
        if cfg['show_corpus_breakdown']:
            _, counts = dominant_corpus(members)
            idx_row['mikra_count'] = counts.get('mikra', 0)
            idx_row['mishna_count'] = counts.get('mishna', 0)
            idx_row['dss_count'] = counts.get('dss', 0)
        index_rows.append(idx_row)

    return pd.DataFrame(top_rows), pd.DataFrame(dist_rows), pd.DataFrame(gap_rows), pd.DataFrame(index_rows)



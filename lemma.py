# ── Precompute: each book's distance to its OWN corpus centroid ────────────
def dist_to_own_centroid(book, mat, centroids):
    corpus = book_corpus_map.get(book)
    cv = centroids.get(corpus)
    if book not in mat.index or cv is None:
        return np.nan
    bv = mat.loc[book].values.reshape(1, -1)
    return float(1 - cosine_similarity(bv, cv.values.reshape(1, -1)))


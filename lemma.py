# ── STEP 2: distance matrices used for the consistency check and Cell 7 ───────
print("\n" + "─" * 60)
print(f"STEP 2: Consistency cross-check (SVD={n_best}, top-{TOP_K} neighbours)")
print("─" * 60)

euclid_svd = pd.DataFrame(squareform(pdist(X_best, metric='euclidean')), index=books_all, columns=books_all)
cos_svd    = pd.DataFrame(pairwise_distances(X_best, metric='cosine'), index=books_all, columns=books_all)
cos_raw    = pd.DataFrame(pairwise_distances(vectors_all, metric='cosine'), index=books_all, columns=books_all)

# Merge-height matrix from Z_best (cophenetic-style pairwise merge heights)
merge_height = np.full((n_books, n_books), np.inf)
np.fill_diagonal(merge_height, 0.0)
cluster_members = {i: [i] for i in range(n_books)}

for step, (left, right, height, _) in enumerate(Z_best):
    left, right = int(left), int(right)
    new_id = n_books + step
    lm = cluster_members.get(left, [left])
    rm = cluster_members.get(right, [right])
    for i in lm:
        for j in rm:
            merge_height[i, j] = height
            merge_height[j, i] = height
    cluster_members[new_id] = lm + rm

merge_height_df = pd.DataFrame(merge_height, index=books_all, columns=books_all)
ward_dist = merge_height_df   # alias used by Cell 7

def get_top_neighbors(book, dist_df, k):
    return dist_df.loc[book].drop(index=book).nsmallest(k).index.tolist()

def cross_check_book(book, k=TOP_K):
    nd = set(get_top_neighbors(book, merge_height_df, k))
    eu = set(get_top_neighbors(book, euclid_svd, k))
    co = set(get_top_neighbors(book, cos_svd, k))
    return {'book': book, 'corpus': book_corpus_map.get(book, 'unknown'),
            'n_consistent': len(nd & eu & co)}

results_cc = [cross_check_book(b) for b in books_all]
total_consistent = sum(r['n_consistent'] for r in results_cc)
max_possible = n_books * TOP_K
print(f"Consistent (SVD={n_best}): {total_consistent}/{max_possible} ({100*total_consistent/max_possible:.1f}%)")

# ── STEP 3: plot the winning Ward dendrogram ───────────────────────────────────
print("\n" + "─" * 60)
print(f"STEP 3: Ward dendrogram (SVD={n_best} components)")
print("─" * 60)


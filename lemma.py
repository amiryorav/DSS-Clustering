ax.set_xlabel("Text", fontsize=11)
ax.set_ylabel("Euclidean Distance (SVD space)", fontsize=11)
ax.grid(axis='y', alpha=0.3, linestyle='--')
ax.legend(handles=legend_handles, loc='upper right', fontsize=10, title='Corpus', framealpha=0.9)
plt.tight_layout()


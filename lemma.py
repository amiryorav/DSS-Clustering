"""
CELL 2: DATA LOADING AND FILTERING
Loads the master dataset and applies three row-level filters:
  1. row_type == 'NNN'
  2. non-empty clean_lemma
  3. book must have >= 100 entries after the above filters
"""

import pandas as pd

def load_and_prepare_lemma_data():
    print("\n📁 LOADING AND PREPARING LEMMA DATA")
    print("-" * 50)

    master_file = f'{DATA_DIR}/master_dataset.pkl'
    print(f"Loading master dataset from: {master_file}")
    df = pd.read_pickle(master_file)
    print(f"Columns: {list(df.columns)}")

    initial_rows = len(df)
    initial_books = df['book'].nunique()

    # --- Filter 1: NNN row type ---
    df = df[df['row_type'] == 'NNN']
    assert not df.empty, "NNN filter removed all rows"

    # --- Filter 2: drop rows with missing/empty clean_lemma ---
    df['clean_lemma'] = df['clean_lemma'].astype(str)
    df = df[df['clean_lemma'].notna() & (df['clean_lemma'].str.strip() != '') & (df['clean_lemma'].str.lower() != 'nan')]
    assert not df.empty, "Empty clean_lemma filter removed all rows"

    after_clean_rows  = len(df)
    after_clean_books = df['book'].nunique()

    # --- Filter 3: keep books with >= 100 entries ---
    book_counts = df['book'].value_counts()
    books_to_keep = book_counts[book_counts >= 100].index
    df = df[df['book'].isin(books_to_keep)].copy()

    final_rows  = len(df)
    final_books = df['book'].nunique()

    print(f"\n📊 FILTER SUMMARY:")
    print(f"  Initial:              {initial_rows:,} rows, {initial_books} books")
    print(f"  After NNN filter:     — ")
    print(f"  After empty-lemma filter: {after_clean_rows:,} rows, {after_clean_books} books")
    print(f"  After ≥100-entries filter: {final_rows:,} rows, {final_books} books")
    print(f"  Total removed:        {initial_rows - final_rows:,} rows, {initial_books - final_books} books")

    # Select relevant columns
    required_columns = ['clean_lemma', 'book', 'corpus']
    missing_columns = [c for c in required_columns if c not in df.columns]
    if missing_columns:
        raise ValueError(f"Cannot proceed without columns: {missing_columns}")

    columns_to_keep = ['verse_id'] + required_columns if 'verse_id' in df.columns else required_columns
    df = df[columns_to_keep].copy()
    df = df.dropna(subset=['clean_lemma', 'book', 'corpus'])

    print(f"\n✅ FINAL DATA: {len(df):,} entries, {df['book'].nunique()} books")
    corpus_dist = df['corpus'].value_counts()
    for corpus, count in corpus_dist.items():
        print(f"  {corpus.upper()}: {count:,} entries ({count/len(df)*100:.1f}%)")

    return df


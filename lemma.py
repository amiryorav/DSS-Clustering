"""
CELL 5: SVD (LSA) + L2 NORMALIZE + WARD DENDROGRAM
Sweeps multiple SVD component sizes, L2-normalizes each (standard LSA
pipeline), picks the best by cophenetic correlation, builds the Ward
linkage, runs a neighbour-consistency cross-check, and plots the
winning dendrogram.

Also exposes cos_raw and ward_dist, which the Ward Cluster Comparison
cell (Cell 7) depends on.
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.decomposition import TruncatedSVD
from sklearn.preprocessing import Normalizer
from sklearn.pipeline import make_pipeline
from sklearn.metrics import pairwise_distances
from scipy.cluster.hierarchy import linkage, dendrogram, cophenet
from scipy.spatial.distance import pdist, squareform

CORPUS_COLORS = {'mikra': 'goldenrod', 'mishna': 'green', 'dss': 'royalblue'}
MMT_SCROLLS   = ['4Q394', '4Q395', '4Q396', '4Q397', '4Q398']
color_map     = {**CORPUS_COLORS, 'mmt': 'red', 'unknown': 'grey'}

vectors_all = lemma_all_books_tfidf
books_all   = vectors_all.index.tolist()
n_books     = len(books_all)

SVD_SIZES   = list(range(10, 201, 10))   # 10, 20, 30, ... 200 — finer sweep for a better n_components pick
TOP_K       = 5    # neighbours for consistency check
PLATEAU_MIN = 70    # cophenetic correlation drops steeply below this, then plateaus — see sweep chart

# ── STEP 1: SVD sweep — pick best n_components by cophenetic correlation ──────
print("─" * 60)
print("STEP 1: SVD sweep")
print("─" * 60)
print(f"{'Components':<14} {'Var explained':>14} {'Cophenetic r':>14}")

results_svd = []
for n_components in SVD_SIZES:
    svd        = TruncatedSVD(n_components=n_components, random_state=42)
    normalizer = Normalizer(copy=False)          # L2 normalize
    lsa        = make_pipeline(svd, normalizer)

    X_svd   = lsa.fit_transform(vectors_all)
    var_exp = svd.explained_variance_ratio_.sum()

    Z_svd = linkage(X_svd, method='ward', metric='euclidean', optimal_ordering=True)
    cc, _ = cophenet(Z_svd, pdist(X_svd, metric='euclidean'))

    results_svd.append({'n': n_components, 'var_exp': var_exp, 'cc': cc, 'Z': Z_svd, 'X': X_svd, 'svd': svd})
    print(f"{n_components:<14} {var_exp:>13.1%} {cc:>14.4f}")

# Cophenetic correlation falls steeply at very low n_components (an easier tree
# to fit, not a better one) then plateaus once enough variance is retained.
# Picking the raw global max would just chase that low-n artifact and throw
# away most of the signal, so we pick the best score within the plateau instead.
global_best  = max(results_svd, key=lambda r: r['cc'])
plateau_pool = [r for r in results_svd if r['n'] >= PLATEAU_MIN]
best         = max(plateau_pool, key=lambda r: r['cc']) if plateau_pool else global_best

print(f"\n   (global max cophenetic r was at n={global_best['n']} "
      f"(var={global_best['var_exp']:.1%}, r={global_best['cc']:.4f}) \u2014 "
      f"skipped: below the n\u2265{PLATEAU_MIN} plateau, likely just fitting a coarse split)")
print(f"\u2705 Best (within plateau, n\u2265{PLATEAU_MIN}): {best['n']} components "
      f"(var={best['var_exp']:.1%}, cophenetic r={best['cc']:.4f})")

X_best  = best['X']
Z_best  = best['Z']
n_best  = best['n']
cc_best = best['cc']
X_best_df = pd.DataFrame(X_best, index=books_all)



# ── Plot: SVD components vs variance explained ──────────────────────────────
ns       = [r['n'] for r in results_svd]
var_exps = [r['var_exp'] for r in results_svd]

plt.figure(figsize=(8, 5))
plt.plot(ns, var_exps, marker='o', color='steelblue')
plt.axvline(PLATEAU_MIN, color='gray', linestyle='--', alpha=0.7,
            label=f'Plateau min (n={PLATEAU_MIN})')
plt.axvline(n_best, color='crimson', linestyle='--', alpha=0.7,
            label=f'Selected n={n_best} (cc={cc_best:.4f})')

plt.xlabel('SVD components (n)')
plt.ylabel('Variance explained')
plt.title('SVD Sweep: Variance Explained vs. Number of Components')

def shared_features(group, n=TOP_N):
    va = [b for b in group if b in morph_tfidf_df.index]
    if not va: return pd.Series(dtype=float)
    return morph_tfidf_df.loc[va].mean().nlargest(n)

def diff_features(group_a, group_b, n=TOP_N):
    va = [b for b in group_a if b in morph_tfidf_df.index]
    vb = [b for b in group_b if b in morph_tfidf_df.index]
    if not va or not vb:
        return pd.Series(dtype=float), pd.Series(dtype=float)
    delta = morph_tfidf_df.loc[va].mean() - morph_tfidf_df.loc[vb].mean()
    return delta.nlargest(n), delta.nsmallest(n)

def centroid_distances(group, mat, centroids):
    va = [b for b in group if b in mat.index]
    if not va: return {}
    gv = mat.loc[va].mean().values.reshape(1, -1)
    return {c: float(1 - cosine_similarity(gv, cv.values.reshape(1, -1)))
            for c, cv in centroids.items() if cv is not None}

def intra_group_distance(group, dist_df):
    valid = [b for b in group if b in dist_df.index]
    if len(valid) < 2: return np.nan
    vals = dist_df.loc[valid, valid].values
    return float(np.nanmean(vals[np.triu_indices(len(valid), k=1)]))


def group_avg_purity(members):
    """Average per-book typicality (purity_results) across a group's member books."""
    vals = [purity_results[b]['purity_score'] for b in members if b in purity_results]
    vals = [v for v in vals if not np.isnan(v)]
    return float(np.mean(vals)) if vals else np.nan


def _verdict_for_group(members):
    """Same >-half-genuine / >-half-artifact logic used inline in Cells 9 & 10."""
    if len(members) < 2:
        return 'N/A'
    n_genuine = n_partial = n_artifact = 0
    for book in members:
        v, _ = nn_consistency(book, members)
        if '✅' in v:
            n_genuine += 1
        elif '⚠️' in v:
            n_partial += 1
        elif '❌' in v:
            n_artifact += 1
    if n_genuine > len(members) / 2:
        return '✅ GENUINE SIGNAL'
    elif n_artifact > len(members) / 2:
        return '❌ WARD ARTIFACT'
    else:
        return '⚠️ PARTIAL SIGNAL'



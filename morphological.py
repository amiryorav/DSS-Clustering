print(f"📚 {df['book'].nunique()} books across corpora: {sorted(df['corpus'].unique())}")
print("Ready for Cell 3: Full-Morpheme Feature Construction")

# -*- coding: utf-8 -*-
"""
CELL 3: FULL-MORPHEME FEATURE CONSTRUCTION
Per the linguists' feedback: a morpheme's morphological analysis is not
separable into independent attributes (POS alone, GENDER alone, ...). Each
row's FULL set of present attributes (pos+gender+number+person+tense+
binyan+state+subtype, whichever apply) is joined into ONE feature string -
the unit of analysis is the whole morpheme, not its parts.
Exception: when subtype == 'properName', the row's signature is JUST
'subtype=properName' - no other attributes are attached. Proper names are
treated as their own atomic category regardless of their pos/gender/number/etc.
Method: one-hot encode this per-row full-morpheme signature (still at
per-lemma granularity), then aggregate (sum) up to book level to get a
book x feature sparse count matrix. No splitting into single/pair/triplet
tiers, and no feature filtering - this keeps the full sparse matrix; any
reduction happens later, via SVD.
Requires: df, MORPH_FEATURES  (from Cells 1-2)
"""
print("\n🔧 BUILDING FULL-MORPHEME FEATURES")
print("-" * 50)
available_features = [f for f in MORPH_FEATURES if f in df.columns]
print(f"Morphological attributes used: {available_features}")
# Index of 'subtype' within available_features, so _row_signature can check
# it directly on the positional `values` tuple without a name lookup per row.
subtype_idx = available_features.index('subtype')

# Sentinel strings that mean "this attribute doesn't apply / is missing".
# NOTE: we filter on the ORIGINAL (pre-str-cast) values so real NaN/None
# don't get turned into the literal string 'nan' and baked into signatures.
_MISSING_STRINGS = {'UNKNOWN', 'nan', 'None', 'none', ''}

# ── Build one full-morpheme signature string per row ─────────────────────────
print("Building per-row full-morpheme signatures (one string per lemma row) …")
def _row_signature(values):
    # Proper names get their own atomic signature - no other attributes joined.
    if values[subtype_idx] == 'properName':
        return 'subtype=properName'
    parts = [
        f"{feat}={val}"
        for feat, val in zip(available_features, values)
        if pd.notna(val) and str(val) not in _MISSING_STRINGS
    ]
    return '|'.join(parts) if parts else 'EMPTY'

# Apply on the ORIGINAL (non-stringified) columns so pd.notna() can still
# see real NaNs. Values get str()-ified only inside _row_signature, per field.
morpheme_signature = df[available_features].apply(_row_signature, axis=1)

df_morph = pd.DataFrame({
    'book': df['book'].values,
    'signature': morpheme_signature.values,
})
n_unique_signatures = df_morph['signature'].nunique()
print(f"✅ Unique full-morpheme signatures: {n_unique_signatures:,}")
print(f"   (compare to {sum(df[f].nunique() for f in available_features)} values if features were split individually)")
# ── One-hot encode signatures, then aggregate per book (sparse) ─────────────
print("One-hot encoding per-row signatures and aggregating to book level …")
book_cat      = pd.Categorical(df_morph['book'])
signature_cat = pd.Categorical(df_morph['signature'])
row_idx = book_cat.codes          # which book each row belongs to
col_idx = signature_cat.codes     # which full-morpheme feature each row is
data    = np.ones(len(df_morph), dtype=np.float64)
# COO -> CSR automatically sums duplicate (book, signature) entries,
# which is exactly the one-hot-then-aggregate (groupby-sum) step.
count_matrix_sparse = sp.coo_matrix(
    (data, (row_idx, col_idx)),
    shape=(len(book_cat.categories), len(signature_cat.categories))
).tocsr()
books         = list(book_cat.categories)
feature_names = list(signature_cat.categories)
print(f"✅ Count matrix: {count_matrix_sparse.shape[0]} books × {count_matrix_sparse.shape[1]:,} features")
density = count_matrix_sparse.nnz / (count_matrix_sparse.shape[0] * count_matrix_sparse.shape[1]) * 100
print(f"📈 Density: {density:.2f}%  ({count_matrix_sparse.nnz:,} non-zero entries)")
print(f"\n✅ CELL 3 COMPLETED: Full-morpheme feature matrix built (full sparse matrix, no filtering)")
print("Ready for Cell 4: TF-IDF")

# -*- coding: utf-8 -*-
"""
CELL 4: TF-IDF TRANSFORMATION
Apply TfidfTransformer to the full book x feature sparse count matrix.
Single fit-transform on all books (no train/test split).
Requires: count_matrix_sparse, books, feature_names  (from Cell 3)
"""

print("\n🔄 APPLYING TF-IDF")
print("-" * 50)

tfidf_transformer = TfidfTransformer()
tfidf_sparse = tfidf_transformer.fit_transform(count_matrix_sparse)

print(f"✅ TF-IDF matrix: {tfidf_sparse.shape[0]} books × {tfidf_sparse.shape[1]:,} features")
density = tfidf_sparse.nnz / (tfidf_sparse.shape[0] * tfidf_sparse.shape[1]) * 100
print(f"📈 Density: {density:.2f}%  ({tfidf_sparse.nnz:,} non-zero entries)")

print(f"\n✅ CELL 4 COMPLETED: TF-IDF matrix ready (sparse)")
print("Ready for Cell 5: SVD")

# -*- coding: utf-8 -*-
"""
CELL 5: TRUNCATED SVD
Fine sweep (10 to 200 in steps of 10) and pick the component count that
maximizes cophenetic correlation against a Ward/Euclidean linkage - i.e. the
SVD dimensionality that best preserves the clustering structure of the full
TF-IDF space. Each candidate uses an LSA-style pipeline (TruncatedSVD -> L2
Normalizer), matching the original.

Cophenetic correlation falls steeply at very low n_components (an easier
tree to fit, not a better one - it comes at the cost of throwing away most
of the variance) then plateaus once enough variance is retained. Picking the
raw global max would just chase that low-n artifact, so the best score is
selected from within the post-drop plateau (n >= PLATEAU_MIN) instead.
Requires: tfidf_sparse, books  (from Cell 4)
"""

print("\n🔻 APPLYING TRUNCATED SVD")
print("-" * 50)

PLATEAU_MIN = 50    # cophenetic r drops steeply below this, then plateaus
_max_components = tfidf_sparse.shape[1] - 1   # TruncatedSVD's hard ceiling (n_components <= n_features)
SVD_SIZES = [n for n in range(10, 201, 10) if n <= _max_components] or [max(2, _max_components)]
if SVD_SIZES[-1] < 200:
    print(f"   (feature space only supports up to {_max_components} components \u2014 "
          f"sweep capped at {SVD_SIZES[-1]} instead of 200)")
print(f"{'Components':<14} {'Var explained':>14} {'Cophenetic r':>14}")
print("-" * 44)

svd_results = []
for n_components in SVD_SIZES:
    svd        = TruncatedSVD(n_components=n_components, random_state=42)
    normalizer = Normalizer(copy=False)
    lsa        = make_pipeline(svd, normalizer)
    X_svd      = lsa.fit_transform(tfidf_sparse)

    var_exp = svd.explained_variance_ratio_.sum()
    Z       = linkage(X_svd, method='ward', metric='euclidean', optimal_ordering=True)
    cc, _   = cophenet(Z, pdist(X_svd, metric='euclidean'))

    svd_results.append({'n': n_components, 'var_exp': var_exp, 'cc': cc,
                         'X': X_svd, 'Z': Z, 'svd': svd})
    print(f"{n_components:<14} {var_exp:>13.1%} {cc:>14.4f}")

global_best  = max(svd_results, key=lambda r: r['cc'])
plateau_pool = [r for r in svd_results if r['n'] >= PLATEAU_MIN]
best         = max(plateau_pool, key=lambda r: r['cc']) if plateau_pool else global_best

X_best    = best['X']
Z_best    = best['Z']
svd_best  = best['svd']
n_best    = best['n']
cc_best   = best['cc']
X_best_df = pd.DataFrame(X_best, index=books)

print(f"\n{'-' * 44}")
print(f"   (global max cophenetic r was at n={global_best['n']} "
      f"(var={global_best['var_exp']:.1%}, r={global_best['cc']:.4f}) \u2014 "
      f"skipped: below the n\u2265{PLATEAU_MIN} plateau, likely just fitting a coarse split)")
print(f"✅ Best (within plateau, n\u2265{PLATEAU_MIN}): {n_best} components "
      f"(var explained = {best['var_exp']:.1%}, cophenetic r = {cc_best:.4f})")

print(f"\n✅ CELL 5 COMPLETED: SVD fitted, {n_best} components selected")
print("Ready for Cell 6: 3D Visualization")

# ── Plot: SVD components vs variance explained ──────────────────────────────
ns       = [r['n'] for r in svd_results]
var_exps = [r['var_exp'] for r in svd_results]

plt.figure(figsize=(8, 5))
plt.plot(ns, var_exps, marker='o', color='steelblue')
plt.axvline(PLATEAU_MIN, color='gray', linestyle='--', alpha=0.7,
            label=f'Plateau min (n={PLATEAU_MIN})')
plt.axvline(n_best, color='crimson', linestyle='--', alpha=0.7,
            label=f'Selected n={n_best} (cc={cc_best:.4f})')

plt.xlabel('SVD components (n)')
plt.ylabel('Variance explained')
plt.title('SVD Sweep: Variance Explained vs. Number of Components')
plt.legend()
plt.grid(alpha=0.3)
plt.tight_layout()
plt.savefig(f'{PLOTS_DIR}/svd_variance_explained.png', dpi=150)
plt.show()


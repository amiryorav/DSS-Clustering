    svd_nn  = set(cos_svd.loc[book].drop(index=book).nsmallest(TOP_K).index)
    ward_nn = set(ward_dist.loc[book].drop(index=book).nsmallest(TOP_K).index)
    all3    = sorted(raw_nn & svd_nn & ward_nn)

    partners  = set(cluster_group) - {book}
    views_hit = sum([bool(partners & raw_nn),
                     bool(partners & svd_nn),
                     bool(partners & ward_nn)])
    verdict = '✅ Genuine' if views_hit >= 2 else \
              ('⚠️ Partial' if views_hit == 1 else '❌ Artifact')
    return verdict, all3


def _style_and_layout(ws, ncols, nrows, corpus_col_idx=None, corpus_values=None):
    ws.row_dimensions[1].height = 30
    for c in range(1, ncols + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
    ws.freeze_panes = 'A2'
    ws.auto_filter.ref = ws.dimensions
    sample_rows = min(nrows, 200)
    for c in range(1, ncols + 1):
        letter = get_column_letter(c)
        max_len = max((len(str(ws.cell(row=r, column=c).value or '')) for r in range(1, sample_rows + 1)),
                      default=10)
        ws.column_dimensions[letter].width = min(max(max_len + 2, 10), 55)
    if corpus_col_idx and corpus_values is not None:
        for i, val in enumerate(corpus_values, start=2):
            fill = CORPUS_FILL.get(str(val).lower())
            if fill:
                ws.cell(row=i, column=corpus_col_idx).fill = fill



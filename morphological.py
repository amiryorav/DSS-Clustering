# -*- coding: utf-8 -*-
"""
CELL 7: DENDROGRAM ON SVD SPACE (WITH WARD-SKEW ANNOTATION)
Ward/Euclidean hierarchical clustering on the full best-SVD space (same
linkage method and metric as the original notebook). A book is flagged as
skewed by Ward when its dendrogram neighbours disagree with its nearest
neighbours under plain Euclidean and cosine distance in the same SVD space
(top-5 neighbour overlap across all three views < 0.2) - such books are
likely placed where they are because of the Ward merge criterion rather
than genuine similarity, and are greyed out / italicized as leaf labels.
Requires: X_best, Z_best, n_best, cc_best, books, book_corpus_map,
          CORPUS_COLORS, PLOTS_DIR  (from Cells 1, 2, 5)
"""

print("\n🌳 BUILDING ANNOTATED DENDROGRAM")
print("-" * 50)

TOP_K = 5
CONSISTENCY_THRESHOLD = 0.2
n_books = len(books)

# MMT scrolls get a dedicated red label color, matching the original notebook
MMT_SCROLLS = ['4Q394', '4Q395', '4Q396', '4Q397', '4Q398']

# ── Distances in SVD space (two independent views) ───────────────────────────
euclid_svd = pd.DataFrame(squareform(pdist(X_best, metric='euclidean')), index=books, columns=books)
cos_svd    = pd.DataFrame(pairwise_distances(X_best, metric='cosine'), index=books, columns=books)

# ── Ward merge height between every pair of books (third view) ──────────────
merge_height = np.full((n_books, n_books), np.inf)
np.fill_diagonal(merge_height, 0.0)
cluster_members = {i: [i] for i in range(n_books)}
for step, (left, right, height, _) in enumerate(Z_best):
    left, right = int(left), int(right)
    lm = cluster_members.get(left,  [left])
    rm = cluster_members.get(right, [right])
    for i in lm:
        for j in rm:
            merge_height[i, j] = height
            merge_height[j, i] = height
    cluster_members[n_books + step] = lm + rm
merge_height_df = pd.DataFrame(merge_height, index=books, columns=books)

# ── Consistency score per book: overlap of top-K neighbours across 3 views ──
def top_neighbors(book, dist_df, k):
    return set(dist_df.loc[book].drop(index=book).nsmallest(k).index)

consistency_scores = {}
for book in books:
    nd = top_neighbors(book, merge_height_df, TOP_K)   # Ward dendrogram view
    eu = top_neighbors(book, euclid_svd, TOP_K)         # Euclidean view
    co = top_neighbors(book, cos_svd, TOP_K)            # Cosine view
    consistency_scores[book] = len(nd & eu & co) / TOP_K

UNRELIABLE = {b for b, s in consistency_scores.items() if s < CONSISTENCY_THRESHOLD}
print(f"Books flagged as skewed by Ward clustering (consistency < {CONSISTENCY_THRESHOLD}): "
      f"{len(UNRELIABLE)} / {n_books}")
if UNRELIABLE:
    print(f"  {sorted(UNRELIABLE)}")

# ── Plot ──────────────────────────────────────────────────────────────────────
legend_handles = [
    plt.Line2D([0], [0], color='goldenrod', lw=4, label='Mikra'),
    plt.Line2D([0], [0], color='green',     lw=4, label='Mishna'),
    plt.Line2D([0], [0], color='royalblue', lw=4, label='DSS'),
    plt.Line2D([0], [0], color='red', lw=4, label='MMT (4Q394-398)'),
    plt.Line2D([0], [0], color='grey', lw=2, linestyle='--',
               label=f'Skewed by Ward (consistency < {CONSISTENCY_THRESHOLD})'),
]

fig, ax = plt.subplots(figsize=(26, 12))
fig.suptitle(
    f"Morphological TF-IDF — Ward Dendrogram (SVD {n_best} components · {n_books} books)\n"
    f"Grey italic = skewed by Ward clustering  ·  Cophenetic r = {cc_best:.4f}",
    fontsize=14, fontweight='bold'
)

dendrogram(
    Z_best,
    labels=books,
    leaf_rotation=90,
    leaf_font_size=5.5,
    color_threshold=Z_best[-8, 2],
    above_threshold_color='lightgray',
    ax=ax,
)

for lbl in ax.get_xmajorticklabels():
    name = lbl.get_text()
    if name in UNRELIABLE:
        lbl.set_color('grey')
        lbl.set_style('italic')
        lbl.set_fontsize(4.5)
    elif name in MMT_SCROLLS:
        lbl.set_color('red')
        lbl.set_fontweight('bold')
    else:
        lbl.set_color(CORPUS_COLORS.get(book_corpus_map.get(name, 'unknown'), 'black'))

ax.set_xlabel("Book  (italic grey = skewed by Ward clustering  ·  red = MMT)", fontsize=10)
ax.set_ylabel("Euclidean Distance (SVD space)", fontsize=10)
ax.grid(axis='y', alpha=0.3, linestyle='--')
ax.legend(handles=legend_handles, loc='upper right', fontsize=9, title='Corpus', framealpha=0.9)

plt.tight_layout()
PDF_PATH = f'{PLOTS_DIR}/morphological_dendrogram_svd{n_best}.pdf'
plt.savefig(PDF_PATH, bbox_inches='tight')
plt.show()

print(f"\n✅ CELL 7 COMPLETED: Annotated dendrogram saved")
print(f"💾 {PDF_PATH}")

# -*- coding: utf-8 -*-
"""
CELL 8: 3D VISUALIZATION OF SVD (COMPONENTS 2-4)
Same idea as Cell 6, but skips SVD component 1 and plots components 2, 3, 4
instead. Component 1 in a (non-centered) TruncatedSVD often captures a
shared "scale" direction with high singular value but low variance across
books (see discussion above) - dropping it is common LSA practice and lets
the remaining axes reflect book-to-book differences more directly.
Requires: X_best, svd_best, n_best, books, book_corpus_map, CORPUS_HEX, PLOTS_DIR
"""


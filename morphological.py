def write_excel_workbook(phase_dir, cfg, top_df, dist_df, gap_df, index_df, n_groups):
    xlsx_path = f"{phase_dir}/{cfg['phase_key']}_tables.xlsx"

    ov = _prepare_excel_index_df(index_df, cfg)
    top_x = _prepare_excel_word_df(top_df, cfg, 'mean_tfidf', 'Importance Score')
    dist_x = _prepare_excel_word_df(dist_df, cfg, 'delta_tfidf_vs_rest', 'Distinctiveness Score')
    gap_x = _prepare_excel_word_df(gap_df, cfg, 'abs_delta_tfidf_vs_nearest', 'Gap Score')

    with pd.ExcelWriter(xlsx_path, engine='openpyxl') as writer:
        wb = writer.book
        ws_instr = wb.active if len(wb.sheetnames) == 1 else wb.create_sheet('How to Use This File', 0)
        ws_instr.title = 'How to Use This File'
        _write_instructions_sheet(ws_instr, cfg, n_groups, TOP_N_PAPER)

        ov.to_excel(writer, sheet_name=cfg['sheet_overview'], index=False)
        top_x.to_excel(writer, sheet_name=cfg['sheet_top'], index=False)
        dist_x.to_excel(writer, sheet_name=cfg['sheet_dist'], index=False)
        gap_x.to_excel(writer, sheet_name=cfg['sheet_gap'], index=False)

        ws_ov = writer.sheets[cfg['sheet_overview']]
        corpus_idx = list(ov.columns).index(cfg['corpus_col_label']) + 1 if cfg['corpus_col_mode'] != 'none' else None
        corpus_vals = ov[cfg['corpus_col_label']].tolist() if corpus_idx else None
        _style_and_layout(ws_ov, ov.shape[1], ov.shape[0] + 1, corpus_idx, corpus_vals)

        for df_x, key in [(top_x, 'sheet_top'), (dist_x, 'sheet_dist'), (gap_x, 'sheet_gap')]:
            ws_d = writer.sheets[cfg[key]]
            c_idx = list(df_x.columns).index(cfg['corpus_col_label']) + 1 if cfg['corpus_col_mode'] != 'none' else None
            c_vals = df_x[cfg['corpus_col_label']].tolist() if c_idx else None
            _style_and_layout(ws_d, df_x.shape[1], df_x.shape[0] + 1, c_idx, c_vals)

        _add_overview_charts(ws_ov, cfg, ov)

        ws_explore = wb.create_sheet(cfg['sheet_explore'])
        _build_explore_sheet(ws_explore, cfg, ov, top_x, dist_x, gap_x)

        wb.active = 0

    return xlsx_path


